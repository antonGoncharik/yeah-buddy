/**
 * Fetches MIT-licensed paths from react-native-body-highlighter and writes
 * src/lib/workout/muscle-body-paths.ts
 */
import { writeFile } from "node:fs/promises";

const VERSION = "v3.1.3";
const BASE = `https://raw.githubusercontent.com/HichamELBSI/react-native-body-highlighter/${VERSION}/assets`;

const FRONT_SLUGS = new Set([
  "chest",
  "obliques",
  "abs",
  "biceps",
  "triceps",
  "forearm",
  "quadriceps",
  "adductors",
  "calves",
  "tibialis",
  "trapezius",
  "deltoids",
]);

const BACK_SLUGS = new Set([
  "trapezius",
  "deltoids",
  "upper-back",
  "triceps",
  "lower-back",
  "forearm",
  "gluteal",
  "adductors",
  "hamstring",
  "calves",
]);

function extractPaths(tsSource) {
  const out = {};
  const slugRe = /slug:\s*"([^"]+)"/g;
  const indices = [];
  let match = slugRe.exec(tsSource);
  while (match !== null) {
    indices.push({ slug: match[1], index: match.index });
    match = slugRe.exec(tsSource);
  }

  for (let i = 0; i < indices.length; i += 1) {
    const { slug, index } = indices[i];
    const end = indices[i + 1]?.index ?? tsSource.length;
    const block = tsSource.slice(index, end);
    const paths = [];
    const pathRe = /"([^"]+)"/g;
    let inPath = false;
    for (const line of block.split("\n")) {
      if (line.includes("path:")) {
        inPath = true;
      }
      if (!inPath) {
        continue;
      }
      let pathMatch = pathRe.exec(line);
      while (pathMatch !== null) {
        const value = pathMatch[1];
        if (value.startsWith("M") || value.startsWith("m")) {
          paths.push(value);
        }
        pathMatch = pathRe.exec(line);
      }
      if (inPath && line.trim() === "},") {
        break;
      }
    }
    if (paths.length > 0) {
      out[slug] = paths;
    }
  }
  return out;
}

async function main() {
  const [frontRaw, backRaw] = await Promise.all([
    fetch(`${BASE}/bodyFront.ts`).then((r) => r.text()),
    fetch(`${BASE}/bodyBack.ts`).then((r) => r.text()),
  ]);

  const frontAll = extractPaths(frontRaw);
  const backAll = extractPaths(backRaw);

  const front = {};
  for (const slug of FRONT_SLUGS) {
    if (frontAll[slug]) {
      front[slug] = frontAll[slug];
    }
  }
  const back = {};
  for (const slug of BACK_SLUGS) {
    if (backAll[slug]) {
      back[slug] = backAll[slug];
    }
  }

  const content = `// Generated by scripts/build-muscle-body-paths.mjs — paths from react-native-body-highlighter (MIT).

export const MUSCLE_BODY_VIEWBOX = "0 0 724 1450";

export const MUSCLE_BODY_PATHS_FRONT: Record<string, string[]> = ${JSON.stringify(front, null, 2)};

export const MUSCLE_BODY_PATHS_BACK: Record<string, string[]> = ${JSON.stringify(back, null, 2)};
`;

  await writeFile("src/lib/workout/muscle-body-paths.ts", content);
  console.log(
    `wrote ${Object.keys(front).length} front slugs, ${Object.keys(back).length} back slugs`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
