export function guidePageText(page: GuidePage): string {
  return [
    page.title,
    page.lead,
    ...page.paragraphs,
    ...(page.points ?? []),
    page.remember ?? "",
  ]
    .filter((line) => line.length > 0)
    .join("\n");
}

export function guideAllText(): string {
  return [
    ...GUIDE_PAGES.map(guidePageText),
    ...GUIDE_TIPS.map((tip) => `${tip.title}\n${tip.body}`),
  ].join("\n");
}

export function guidePageById(id: string): GuidePage | null {
  return GUIDE_PAGES.find((page) => page.id === id) ?? null;
}

export function guideTipById(id: GuideTip["id"]): GuideTip | null {
  return GUIDE_TIPS.find((tip) => tip.id === id) ?? null;
}
